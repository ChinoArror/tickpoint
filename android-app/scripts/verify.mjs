#!/usr/bin/env node
// Verifies the release artifacts in android-app/artifacts with the official Android tools:
//   apksigner (signature, signer certificate), aapt2 (package, version, SDK levels, permissions),
//   jarsigner (AAB signature), and SHA256SUMS. Fails loudly on any mismatch.
//
//   node scripts/verify.mjs            (version from android-app/package.json)
//   node scripts/verify.mjs 1.0.0      (explicit version)
import { createHash } from 'node:crypto'
import { createReadStream, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import {
  APP_ID,
  ARTIFACTS,
  EXPECTED_CERT_SHA256,
  aapt2,
  apksigner,
  artifactNames,
  exe,
  javaHome,
  run,
  normalizeFingerprint,
  parseBadging,
  readPackageVersion,
} from './lib/android.mjs'

/** Permissions this app may hold. Anything else fails verification. */
export const ALLOWED_PERMISSIONS = [
  'android.permission.INTERNET',
  'android.permission.POST_NOTIFICATIONS',
]

/**
 * Permissions the Firebase Messaging dependencies declare (firebase-messaging, firebase-installations,
 * play-services-cloud-messaging, the Google datatransport libraries). FCM needs them for background
 * delivery and connectivity checks, so the app keeps them. Removing them would break push.
 * DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION is generated by AGP for dynamically registered receivers.
 */
export const KNOWN_FCM_PERMISSIONS = [
  'android.permission.WAKE_LOCK',
  'android.permission.ACCESS_NETWORK_STATE',
  'com.google.android.c2dm.permission.RECEIVE',
  `${APP_ID}.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION`,
]

export function sha256File(path) {
  return new Promise((resolve, reject) => {
    const hash = createHash('sha256')
    createReadStream(path)
      .on('data', (chunk) => hash.update(chunk))
      .on('error', reject)
      .on('end', () => resolve(hash.digest('hex')))
  })
}

/** Checks the release artifacts for `version`. Returns a summary. Throws on any failure. */
export async function verifyArtifacts({ version = readPackageVersion(), log = console.log, checkSums = true } = {}) {
  const names = artifactNames(version)
  const apkPath = join(ARTIFACTS, names.apk)
  const aabPath = join(ARTIFACTS, names.aab)
  if (!existsSync(apkPath)) throw new Error(`Missing ${apkPath}. Run "npm run release" first.`)

  // 1. APK signature and signer certificate
  const sig = apksigner(['verify', '--verbose', '--print-certs', apkPath], { check: false })
  const sigText = `${sig.stdout}${sig.stderr}`
  writeFileSync(join(ARTIFACTS, 'apksigner-verify.txt'), sigText)
  if (sig.status !== 0 || !/Verifies/.test(sigText)) throw new Error(`apksigner verify failed:\n${sigText}`)
  if (!/Verified using v2 scheme \(APK Signature Scheme v2\): true|Verified using v3 scheme \(APK Signature Scheme v3\): true/.test(sigText)) {
    throw new Error('APK is not signed with APK Signature Scheme v2 or v3.')
  }
  if (/CN=Android Debug/.test(sigText)) throw new Error('APK is signed with the Android debug certificate. Refusing.')
  const digests = [...sigText.matchAll(/Signer #\d+ certificate SHA-256 digest: ([0-9a-fA-F:]+)/g)].map((m) => m[1])
  if (digests.length !== 1) throw new Error(`Expected exactly one signer, found ${digests.length}.`)
  if (normalizeFingerprint(digests[0]) !== normalizeFingerprint(EXPECTED_CERT_SHA256)) {
    throw new Error(`Signer SHA-256 ${digests[0]} does not match the release certificate.`)
  }

  // 2. Package metadata and permissions
  const info = parseBadging(aapt2(['dump', 'badging', apkPath]).stdout)
  if (info.packageName !== APP_ID) throw new Error(`Package is ${info.packageName}, expected ${APP_ID}.`)
  if (info.versionName !== version) throw new Error(`versionName is ${info.versionName}, expected ${version}.`)
  if (!info.minSdk || info.minSdk < 24) throw new Error(`minSdk ${info.minSdk} is below the supported floor (24).`)
  if (!info.targetSdk || info.targetSdk < 36) throw new Error(`targetSdk ${info.targetSdk} is below 36 (Google Play requirement).`)
  const unexpected = info.permissions.filter((p) => !ALLOWED_PERMISSIONS.includes(p) && !KNOWN_FCM_PERMISSIONS.includes(p))
  if (unexpected.length) throw new Error(`Unexpected permissions in the merged manifest: ${unexpected.join(', ')}`)

  // 3. AAB signer. jarsigner cannot build a trust path for the self-generated upload key, so the
  //    certificate is read from the signature block (keytool -printcert -jarfile) and compared with
  //    the release fingerprint. The AAB's signature is not trust-validated by this check.
  let aab = null
  if (existsSync(aabPath)) {
    const kt = run(join(javaHome(), 'bin', exe('keytool')), ['-printcert', '-jarfile', aabPath], { check: false, label: 'keytool' })
    const ktText = `${kt.stdout}${kt.stderr}`
    const match = ktText.match(/SHA256:\s*([0-9A-Fa-f:]{95})/)
    if (kt.status !== 0 || !match) throw new Error(`Could not read the signing certificate from the AAB:\n${ktText}`)
    if (/CN=Android Debug/.test(ktText)) throw new Error('AAB is signed with the Android debug certificate. Refusing.')
    if (normalizeFingerprint(match[1]) !== normalizeFingerprint(EXPECTED_CERT_SHA256)) {
      throw new Error(`AAB signer SHA-256 ${match[1]} does not match the release certificate.`)
    }
    aab = { path: aabPath, signerSha256: normalizeFingerprint(match[1]) }
  }

  // 4. Checksums, when a SHA256SUMS.txt is present, must still match the files (the release step
  //    skips this because it rewrites SHA256SUMS.txt right after verifying a fresh build)
  const sums = {}
  sums.apk = await sha256File(apkPath)
  if (aab) sums.aab = await sha256File(aabPath)
  const sumsPath = join(ARTIFACTS, 'SHA256SUMS.txt')
  if (checkSums && existsSync(sumsPath)) {
    const lines = readFileSync(sumsPath, 'utf8').trim().split('\n')
    for (const [name, hash] of [[names.apk, sums.apk], [names.aab, sums.aab]]) {
      if (!hash) continue
      const line = lines.find((l) => l.endsWith(` ${name}`) || l.endsWith(`*${name}`))
      if (!line || !line.startsWith(hash)) throw new Error(`SHA256SUMS.txt does not match ${name}.`)
    }
  }

  const summary = {
    version,
    apk: { path: apkPath, sha256: sums.apk },
    aab,
    signerSha256: normalizeFingerprint(digests[0]),
    packageName: info.packageName,
    versionCode: info.versionCode,
    versionName: info.versionName,
    minSdk: info.minSdk,
    targetSdk: info.targetSdk,
    permissions: info.permissions,
    launchableActivity: info.launchableActivity,
  }
  log(`verified ${names.apk}`)
  log(`  package ${info.packageName} versionName ${info.versionName} versionCode ${info.versionCode}`)
  log(`  minSdk ${info.minSdk} targetSdk ${info.targetSdk}`)
  log(`  signer SHA-256 ${digests[0]}`)
  log(`  permissions: ${info.permissions.join(', ')}`)
  log(`  apk sha256 ${sums.apk}`)
  if (aab) log(`  aab signer ${aab.signerSha256}`)
  return summary
}

// Run directly: node scripts/verify.mjs [version]
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const version = process.argv[2] ?? readPackageVersion()
  verifyArtifacts({ version }).catch((e) => {
    console.error(`VERIFY FAILED: ${e.message}`)
    process.exit(1)
  })
}
