#!/usr/bin/env node
// Builds the release APK and AAB, copies them into android-app/artifacts, verifies the signature
// and package, and writes SHA256SUMS.txt and BUILD_INFO.md.
//
//   cd android-app && npm run release
//
// Needs: JAVA_HOME (JDK 21), ANDROID_HOME (SDK with platform 36 and build-tools 36.0.0), and the
// signing properties file (TICKPOINT_SIGNING_PROPS, or <home>/.tickpoint-signing/keystore.properties).
// The signing passwords are read by Gradle only. This script never reads or prints them.
//
//   node scripts/release.mjs --skip-build   re-copy, verify and write checksums from the last Gradle outputs
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import {
  ANDROID,
  ANDROID_APP,
  ARTIFACTS,
  BUILD_TOOLS_VERSION,
  REPO,
  artifactNames,
  javaHome,
  readGradleVersion,
  readPackageVersion,
  run,
  sdkRoot,
} from './lib/android.mjs'
import { verifyArtifacts, sha256File } from './verify.mjs'

const isWin = process.platform === 'win32'

function step(title) {
  console.log(`\n== ${title}`)
}

function gitCommit() {
  const res = run('git', ['rev-parse', '--short', 'HEAD'], { cwd: REPO, check: false })
  return res.status === 0 ? res.stdout.trim() : 'unknown'
}

function javaVersion() {
  const res = run(join(javaHome(), 'bin', isWin ? 'java.exe' : 'java'), ['-version'], { check: false })
  return `${res.stderr}${res.stdout}`.split('\n')[0].trim()
}

function gradleDistribution() {
  const text = readFileSync(join(ANDROID, 'gradle', 'wrapper', 'gradle-wrapper.properties'), 'utf8')
  return text.match(/gradle-([\d.]+)-/)?.[1] ?? 'unknown'
}

function agpVersion() {
  const text = readFileSync(join(ANDROID, 'build.gradle'), 'utf8')
  return text.match(/com\.android\.tools\.build:gradle:([\d.]+)/)?.[1] ?? 'unknown'
}

function variable(name) {
  const text = readFileSync(join(ANDROID, 'variables.gradle'), 'utf8')
  return text.match(new RegExp(`${name}\\s*=\\s*(\\d+)`))?.[1] ?? 'unknown'
}

function capacitorVersion() {
  const pkg = JSON.parse(readFileSync(join(ANDROID_APP, 'package.json'), 'utf8'))
  return pkg.dependencies['@capacitor/core']
}

function minifyEnabled(flag) {
  const text = readFileSync(join(ANDROID, 'app', 'build.gradle'), 'utf8')
  const release = text.slice(text.indexOf('buildTypes'))
  return new RegExp(`${flag}\\s+true`).test(release) ? 'yes' : 'no'
}

async function main() {
  const version = readPackageVersion()
  const gradleVersion = readGradleVersion()
  if (gradleVersion.versionName !== version) {
    throw new Error(`versionName in android/app/build.gradle (${gradleVersion.versionName}) must equal package.json (${version}).`)
  }
  const names = artifactNames(version)

  const skipBuild = process.argv.includes('--skip-build')
  if (!skipBuild) {
  step('Build web bundle and sync Capacitor')
  run('npm', ['run', 'sync'], { cwd: ANDROID_APP, shell: true, label: 'npm run sync' })

  step('Gradle: clean assembleRelease bundleRelease')
  // Full paths: cmd does not search the working directory (NoDefaultCurrentDirectoryInExePath).
  const gradle = isWin ? ['cmd', ['/c', join(ANDROID, 'gradlew.bat')]] : [join(ANDROID, 'gradlew'), []]
  run(gradle[0], [...gradle[1], '--console=plain', '--no-daemon', 'clean', 'assembleRelease', 'bundleRelease'], {
    cwd: ANDROID,
    label: 'gradle',
  })
  } else {
    step('Reusing existing Gradle outputs (--skip-build)')
  }

  const apkBuilt = join(ANDROID, 'app', 'build', 'outputs', 'apk', 'release', 'app-release.apk')
  const aabBuilt = join(ANDROID, 'app', 'build', 'outputs', 'bundle', 'release', 'app-release.aab')
  if (!existsSync(apkBuilt)) throw new Error(`Gradle did not produce ${apkBuilt}`)
  if (!existsSync(aabBuilt)) throw new Error(`Gradle did not produce ${aabBuilt}`)

  step('Copy artifacts')
  mkdirSync(ARTIFACTS, { recursive: true })
  copyFileSync(apkBuilt, join(ARTIFACTS, names.apk))
  copyFileSync(aabBuilt, join(ARTIFACTS, names.aab))

  step('Verify signature and package')
  const summary = await verifyArtifacts({ version, checkSums: false })

  step('Checksums and build info')
  const apkHash = await sha256File(join(ARTIFACTS, names.apk))
  const aabHash = await sha256File(join(ARTIFACTS, names.aab))
  writeFileSync(join(ARTIFACTS, 'SHA256SUMS.txt'), `${apkHash}  ${names.apk}\n${aabHash}  ${names.aab}\n`)

  const sizes = {
    apk: (readFileSync(join(ARTIFACTS, names.apk)).length / 1024 / 1024).toFixed(2),
    aab: (readFileSync(join(ARTIFACTS, names.aab)).length / 1024 / 1024).toFixed(2),
  }
  const info = `# TickPoint Android build ${version}

Generated by \`android-app/scripts/release.mjs\` on ${new Date().toISOString()}.

| Item | Value |
|---|---|
| Application ID | \`${summary.packageName}\` |
| Version name / code | ${summary.versionName} / ${summary.versionCode} |
| minSdk / targetSdk | ${summary.minSdk} / ${summary.targetSdk} (compileSdk ${variable('compileSdkVersion')}) |
| Release signer SHA-256 | \`${summary.signerSha256}\` (public certificate fingerprint) |
| Signature scheme | APK Signature Scheme v2/v3 (apksigner verified) |
| Minification (R8) / resource shrinking | ${minifyEnabled('minifyEnabled')} / ${minifyEnabled('shrinkResources')} |
| Permissions | ${summary.permissions.map((p) => '`' + p + '`').join(', ')} |
| google-services.json present | ${existsSync(join(ANDROID, 'app', 'google-services.json')) ? 'yes' : 'no (push reports unavailable)'} |
| Git commit | ${gitCommit()} |
| Capacitor | ${capacitorVersion()} |
| Android Gradle Plugin | ${agpVersion()} |
| Gradle | ${gradleDistribution()} |
| Build-tools | ${BUILD_TOOLS_VERSION} |
| Android SDK root | \`${sdkRoot()}\` |
| Java | ${javaVersion()} |
| Node | ${process.version} |

## Files

| File | Size (MiB) | SHA-256 |
|---|---|---|
| \`${names.apk}\` | ${sizes.apk} | \`${apkHash}\` |
| \`${names.aab}\` | ${sizes.aab} | \`${aabHash}\` |

Checks: \`apksigner-verify.txt\` (signature output), \`SHA256SUMS.txt\`. Re-run \`npm run verify\` to repeat the checks.
`
  writeFileSync(join(ARTIFACTS, 'BUILD_INFO.md'), info)
  console.log(`\nRelease ready in ${ARTIFACTS}`)
  console.log(`  ${names.apk}  (${sizes.apk} MiB)  sha256 ${apkHash}`)
  console.log(`  ${names.aab}  (${sizes.aab} MiB)  sha256 ${aabHash}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(`\nRELEASE FAILED: ${e.message}`)
    process.exit(1)
  })
}
