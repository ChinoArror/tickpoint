#!/usr/bin/env node
// Maps .design/secret.json (never committed) into the app's configuration
// without printing secret values.
//
//   node scripts/sync-secrets.mjs --local    writes .dev.vars for `vite dev` / `wrangler dev`
//   node scripts/sync-secrets.mjs --remote   uploads Workers secrets with `wrangler secret put`
//
// Key mapping (secret.json -> app):
//   app-id        -> AUTH_APP_ID (var)
//   app-secret    -> AUTH_APP_SECRET (secret)
//   callback-url  -> AUTH_CALLBACK_URL (var)
//   GeminiApiKey  -> GEMINI_API_KEY (secret)
//   GeminiModel   -> GEMINI_MODEL (var)
//   d1-id/d1-name/r2-name/workers-name -> wrangler.jsonc bindings (non-secret)
// VAPID keys are generated once into .design/vapid.json (git-ignored).

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { webcrypto } from 'node:crypto'

const SECRET_FILE = '.design/secret.json'
const VAPID_FILE = '.design/vapid.json'

if (!existsSync(SECRET_FILE)) {
  console.error(`Missing ${SECRET_FILE}. See docs/CONFIGURATION.md.`)
  process.exit(1)
}
const s = JSON.parse(readFileSync(SECRET_FILE, 'utf8'))

const b64url = (buf) => Buffer.from(buf).toString('base64url')

async function ensureVapid() {
  if (existsSync(VAPID_FILE)) return JSON.parse(readFileSync(VAPID_FILE, 'utf8'))
  const kp = await webcrypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify'])
  const pub = b64url(await webcrypto.subtle.exportKey('raw', kp.publicKey))
  const jwk = await webcrypto.subtle.exportKey('jwk', kp.privateKey)
  const keys = { publicKey: pub, privateKey: jwk.d }
  writeFileSync(VAPID_FILE, JSON.stringify(keys, null, 2))
  console.log('Generated new VAPID key pair in', VAPID_FILE)
  return keys
}

function setWranglerVar(name, value) {
  const path = 'wrangler.jsonc'
  const src = readFileSync(path, 'utf8')
  const re = new RegExp(`("${name}"\\s*:\\s*)"[^"]*"`)
  if (!re.test(src)) return
  writeFileSync(path, src.replace(re, `$1${JSON.stringify(value)}`))
}

const vapid = await ensureVapid()
setWranglerVar('VAPID_PUBLIC_KEY', vapid.publicKey)
if (s['app-id']) setWranglerVar('AUTH_APP_ID', s['app-id'])
if (s['callback-url']) setWranglerVar('AUTH_CALLBACK_URL', s['callback-url'])
if (s['GeminiModel']) setWranglerVar('GEMINI_MODEL', s['GeminiModel'])

const secrets = {
  AUTH_APP_SECRET: s['app-secret'],
  GEMINI_API_KEY: s['GeminiApiKey'],
  VAPID_PRIVATE_KEY: vapid.privateKey,
}
const missing = Object.entries(secrets).filter(([, v]) => !v).map(([k]) => k)
if (missing.length) console.warn('Missing values (left unset):', missing.join(', '))

const mode = process.argv[2]
if (mode === '--local') {
  const lines = [
    '# Generated by scripts/sync-secrets.mjs — do not commit.',
    'APP_ENV=development',
    'APP_ORIGIN=http://localhost:5173',
    'DEV_AUTH_BYPASS=true',
    `VAPID_PUBLIC_KEY=${vapid.publicKey}`,
    ...Object.entries(secrets).filter(([, v]) => v).map(([k, v]) => `${k}=${v}`),
  ]
  writeFileSync('.dev.vars', lines.join('\n') + '\n')
  console.log('Wrote .dev.vars with keys:', ['APP_ENV', 'APP_ORIGIN', 'DEV_AUTH_BYPASS', 'VAPID_PUBLIC_KEY', ...Object.keys(secrets).filter((k) => secrets[k])].join(', '))
} else if (mode === '--remote') {
  for (const [name, value] of Object.entries(secrets)) {
    if (!value) continue
    const r = spawnSync('npx', ['wrangler', 'secret', 'put', name], { input: value, stdio: ['pipe', 'ignore', 'inherit'], shell: process.platform === 'win32' })
    console.log(`${name}: ${r.status === 0 ? 'uploaded' : 'FAILED'}`)
    if (r.status !== 0) process.exitCode = 1
  }
} else {
  console.log('Usage: node scripts/sync-secrets.mjs --local | --remote')
}
